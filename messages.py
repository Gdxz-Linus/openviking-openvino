def verify_keys() -> list[str]:
    """返回任一侧缺失的键；两张表的键集合一致时返回空列表。"""
    all_keys = set(MESSAGES["zh"]) | set(MESSAGES["en"])
    return sorted(
        key
        for key in all_keys
        if key not in MESSAGES["zh"] or key not in MESSAGES["en"]
    )


class Translator:
    """按语言查表并执行命名占位符插值。"""

    def __init__(self, language: str) -> None:
        if language not in MESSAGES:
            raise ValueError(f"Unsupported language: {language}")
        self.language = language
        self._messages = MESSAGES[language]

    def t(self, key: str, **kwargs: Any) -> str:
        try:
            template = self._messages[key]
        except KeyError as exc:
            raise KeyError(f"Unknown message key for {self.language}: {key}") from exc
        return template.format(**kwargs)
